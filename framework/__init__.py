"""Framework package: the group's orchestration architecture applied to the FDM case.

Components, in the order of the information flow (names follow the JIII manuscript):

- ``kinm``   Knowledge and Input Normalisation Module: product features and the machine's
             operation log become records with source provenance and confidence.
- ``spcm``   Sensor-driven Process Characterisation Module (the module this master's adds):
             multivariate sensor series become operational states (patterns, transitions,
             anomalies) with method provenance, linked to operation instances.
- ``cfrm``   Contextual Feature-Rule Mapper: records become ontology individuals; numeric
             qualifiers become asserted classes; evidence classes are asserted from states.
- ``skl``    Structured Knowledge Layer: OWL ontologies generated by script, one rule file,
             a repository that reasons (Python forward chaining here; Pellet where Java exists).
- ``kefc``   Knowledge Extension and Feedback Controller: owns all gating, reason codes and the
             persistent expert-validation store; emits the plan with parameter provenance.
- ``ral``    Responsive Application Layer: serialises only approved steps into a print profile
             and refuses, with a recorded reason, steps whose geometry the plan does not specify.
- ``kg``     Unified application graph (NetworkX) exported to RDF with a fixed SPARQL suite.
- ``main``   One invocation per configuration into a fresh output folder.

External vocabulary (reason codes, statuses, file names, RDF terms) is in English to match the
group's artefacts; the Portuguese modules of this repository are used as libraries underneath.
"""
